export function getIngredientById(id: string): MasterIngredient | undefined {
  return mockIngredients.find(ing => ing.id === id);
}

export function getIngredientsByCategory(category: string): MasterIngredient[] {
  if (category === 'all') return mockIngredients;
  return mockIngredients.filter(ing => ing.category === category);
}

export function searchIngredients(searchTerm: string): MasterIngredient[] {
  const term = searchTerm.toLowerCase();
  return mockIngredients.filter(
    ing =>
      ing.name.toLowerCase().includes(term) ||
      ing.category.toLowerCase().includes(term)
  );
}

export function getLowStockIngredients(): MasterIngredient[] {
  return mockIngredients.filter(
    ing => ing.quantityOnHand <= (ing.reorderLevel || 0)
  );
}

export function getIngredientCategories(): string[] {
  return Array.from(new Set(mockIngredients.map(ing => ing.category)));
}
