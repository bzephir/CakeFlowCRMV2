import { MasterIngredient, calculateCostPerUnit, StorageLocation } from '../types/ingredient';

const createIngredient = (
  id: string,
  name: string,
  category: MasterIngredient['category'],
  packageSize: number,
  packageUnit: MasterIngredient['packageUnit'],
  packageDescription: string,
  purchasePrice: number,
  baseUnit: MasterIngredient['baseUnit'],
  location: StorageLocation,
  vendorId: string,
  quantityOnHand: number = 10,
  reorderLevel: number = 5,
  brand?: string,
  dateReceived?: string,
  lotNumber?: string,
  expirationDate?: string,
  createdAtOverride?: string
): MasterIngredient => {
  const costPerUnit = calculateCostPerUnit(purchasePrice, packageSize, packageUnit, baseUnit);
  return {
    id,
    name,
    category,
    packageSize,
    packageUnit,
    packageDescription,
    quantityOnHand,
    purchasePrice,
    costPerUnit,
    baseUnit,
    location,
    supplierId: vendorId,
    vendorId,
    reorderLevel,
    brand,
    dateReceived,
    expirationDate,
    lotNumber,
    lastPriceUpdate: '2024-01-15T10:00:00Z',
    createdAt: createdAtOverride || '2024-01-01T08:00:00Z',
    updatedAt: '2024-01-15T10:00:00Z'
  };
};

